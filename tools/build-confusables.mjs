#!/usr/bin/env node
// @ts-check
/**
 * Data-build script for the UTS#39 confusables table (LINK-gjlcyrqq / E1).
 *
 * Downloads the official Unicode Security Mechanisms confusables.txt, filters it
 * to a high-risk cross-script subset, and emits a compact, version-pinned TS
 * table at packages/core/src/data/confusables.generated.ts.
 *
 *   node tools/build-confusables.mjs                 # fetch the pinned version
 *   node tools/build-confusables.mjs --input <file>  # parse a local copy
 *   node tools/build-confusables.mjs --check         # fail if output is stale
 *
 * Do NOT hand-edit the generated file. Re-run this script to regenerate it.
 *
 * Bundle-size policy (OQ-1 / NFR-DATA-2/3): we ship a CURATED subset filtered
 * from the official list rather than the full ~6.3k-row table — every source is
 * a non-ASCII Letter/Mark/Number and every target is all-ASCII alphanumeric, so
 * the table covers exactly the cross-script ASCII-lookalikes that drive domain
 * homographs (Cyrillic/Greek/fullwidth/math/etc.) while staying compact. The
 * annotation is informational (weight 0, FR-D-15/16); single-script legitimate
 * IDNs still score 0 (SC-2) because the cross-script de-noiser is mixed_script.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

// ── Pinned source (Unicode 16.0.0, to match the IDNA/tldts baseline) ─────────
const UNICODE_VERSION = "16.0.0";
const VERSION_ID = `uts39-${UNICODE_VERSION}-curated`;
const SOURCE_URL = `https://www.unicode.org/Public/security/${UNICODE_VERSION}/confusables.txt`;

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = resolve(__dirname, "../packages/core/src/data/confusables.generated.ts");

const args = process.argv.slice(2);
const inputIdx = args.indexOf("--input");
const inputPath = inputIdx >= 0 ? args[inputIdx + 1] : null;
const checkOnly = args.includes("--check");

/** Hex codepoint → upper-case `U+XXXX` (min 4 digits). */
function uplus(cp) {
  return `U+${cp.toString(16).toUpperCase().padStart(4, "0")}`;
}

/** Parse confusables.txt into filtered [source, targetString, targetName] rows. */
function parse(text) {
  const rows = [];
  for (const line of text.split(/\r?\n/)) {
    if (!line || line.startsWith("#")) continue;
    const m = /^([0-9A-Fa-f]+)\s*;\s*([0-9A-Fa-f ]+?)\s*;\s*MA/.exec(line);
    if (!m) continue;

    const src = parseInt(m[1], 16);
    // Source must be a single non-ASCII Letter/Mark/Number — the shape of a
    // character that can appear in a host label or path and impersonate ASCII.
    if (src <= 0x7f) continue;
    const srcCh = String.fromCodePoint(src);
    if (!/[\p{L}\p{M}\p{N}]/u.test(srcCh)) continue;

    const targetStr = String.fromCodePoint(...m[2].trim().split(/\s+/).map((h) => parseInt(h, 16)));
    // Target must be all-ASCII alphanumeric (covers single letters/digits and
    // multi-codepoint targets like "rn" → m, "vv" → w).
    if (![...targetStr].every((c) => /[A-Za-z0-9]/.test(c))) continue;

    // Official target name(s), parsed from the trailing comment:
    //   # ( х → x ) CYRILLIC SMALL LETTER HA → LATIN SMALL LETTER X	# …
    const hashIdx = line.indexOf("#");
    const comment = hashIdx >= 0 ? line.slice(hashIdx + 1) : "";
    const afterParen = comment.slice(comment.indexOf(")") + 1).split("\t")[0].trim();
    const arrowIdx = afterParen.indexOf(" → ");
    const targetName = (arrowIdx >= 0 ? afterParen.slice(arrowIdx + 3) : afterParen).trim();

    rows.push([src, targetStr, targetName || targetStr]);
  }
  rows.sort((a, b) => a[0] - b[0]);
  return rows;
}

function render(rows, meta) {
  const lines = rows.map(([src, t, n]) => {
    const cps = [...t].map((c) => uplus(c.codePointAt(0))).join(" ");
    return `  [0x${src.toString(16)}, ${JSON.stringify(t)}, ${JSON.stringify(n)}], // ${cps}`;
  });
  return `// AUTO-GENERATED by tools/build-confusables.mjs — DO NOT EDIT.
// Regenerate with: node tools/build-confusables.mjs
//
// Source:  ${SOURCE_URL}
// Unicode: ${UNICODE_VERSION} · UTS#39 (Unicode Security Mechanisms)
// sha256:  ${meta.sha256}
// License: Unicode Terms of Use (https://www.unicode.org/terms_of_use.html)
//
// Curated subset (OQ-1 / NFR-DATA-2): source = non-ASCII Letter/Mark/Number,
// target = all-ASCII alphanumeric. ${rows.length} entries. Annotation is
// informational only (weight 0, FR-D-15/16); see tools/README.md.

/** Version id stamped into dataVersions.unicodeConfusables. */
export const CONFUSABLES_VERSION = ${JSON.stringify(VERSION_ID)};

/** [sourceCodepoint, targetString, targetName]. Target may be multi-codepoint. */
export type ConfusableRow = readonly [number, string, string];

export const CONFUSABLES_RAW: readonly ConfusableRow[] = [
${lines.join("\n")}
];
`;
}

async function main() {
  let raw;
  if (inputPath) {
    raw = readFileSync(inputPath, "utf8");
  } else {
    process.stderr.write(`Fetching ${SOURCE_URL} …\n`);
    const res = await fetch(SOURCE_URL);
    if (!res.ok) throw new Error(`fetch failed: ${res.status} ${res.statusText}`);
    raw = await res.text();
  }

  const sha256 = createHash("sha256").update(raw).digest("hex");
  const rows = parse(raw);
  if (rows.length === 0) throw new Error("no rows parsed — source format may have changed");
  const out = render(rows, { sha256 });

  if (checkOnly) {
    const current = readFileSync(OUT_PATH, "utf8");
    // Compare ignoring the sha256 line (depends on the exact bytes fetched).
    const strip = (s) => s.replace(/^\/\/ sha256:.*$/m, "");
    if (strip(current) !== strip(out)) {
      process.stderr.write("confusables.generated.ts is STALE — re-run the build script.\n");
      process.exit(1);
    }
    process.stderr.write(`OK — ${rows.length} entries up to date.\n`);
    return;
  }

  writeFileSync(OUT_PATH, out);
  process.stderr.write(`Wrote ${rows.length} entries to ${OUT_PATH}\n`);
}

main().catch((err) => {
  process.stderr.write(`${err.stack || err}\n`);
  process.exit(1);
});
