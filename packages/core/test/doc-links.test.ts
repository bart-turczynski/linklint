/**
 * `gitlabAnchor` against GitLab's own output (LINK-quzdwhjt).
 *
 * Every expectation below is a TRANSCRIPTION of an `id="user-content-…"` read
 * off GitLab's server-rendered HTML for this repository on 2026-09-05, not a
 * derivation from the implementation. They are the cases that discriminate: if
 * a future edit made the slugifier squeeze hyphens, strip marks, or replace
 * punctuation with a separator instead of deleting it, one of these reddens.
 */
describe("gitlabAnchor matches GitLab's rendered ids (LINK-quzdwhjt)", () => {
  it.each([
    // The two anchors that were in conflict. Repeated hyphens SURVIVE.
    ["MCP server — check before you fetch", "mcp-server--check-before-you-fetch"],
    [
      'Gating on results — status: "invalid" must be handled explicitly',
      "gating-on-results--status-invalid-must-be-handled-explicitly",
    ],
    // `&` is DELETED, not replaced — so `A & B` leaves two hyphens, not three.
    ["Scoring & severity", "scoring--severity"],
    // Section numbers lose their dots and run together: 6.1 → 61.
    ["6.1 PSL snapshot provenance & staleness", "61-psl-snapshot-provenance--staleness"],
    // Apostrophes and quotes vanish with no separator at all: aren't → arent.
    [
      '2. Homographs & confusables — "those letters aren\'t what they look like"',
      "2-homographs--confusables--those-letters-arent-what-they-look-like",
    ],
    // `\p{M}`: İ lowercases to i + U+0307, and GitLab KEEPS the combining mark.
    [
      "D2 — collapse (İ → i): the sharp direction, and it is a real gap",
      "d2--collapse-i̇--i-the-sharp-direction-and-it-is-a-real-gap",
    ],
  ])("%s → %s", (text, expected) => {
    expect(gitlabAnchor(text)).toBe(expected);
  });

  it("does not squeeze repeated hyphens (the decision this unit made)", () => {
    // Stated separately from the table because it is the ONE property that
    // decides which of the two conflicting spellings was correct. GitHub's
    // slugifier collapses here; GitLab's does not, and GitLab is where these
    // docs are read.
    expect(gitlabAnchor("a — b")).toBe("a--b");
    expect(gitlabAnchor("a — b")).not.toBe("a-b");
  });

  it("reads the heading text out of the markdown line, markup and all", () => {
    expect(headingText('### Gating on results — `status: "invalid"` must be handled explicitly')).toBe(
      'Gating on results — status: "invalid" must be handled explicitly',
    );
    expect(headingText("## MCP server — check before you fetch")).toBe(
      "MCP server — check before you fetch",
    );
    expect(headingText("### **Bold** and _thin_ and [linked](./x.md)")).toBe(
      "Bold and thin and linked",
    );
  });

  it("a fragment that names no heading is REPORTED MISSING, not skipped", () => {
    // The fragment half of the guard reduces to this one lookup, exactly as the
    // path half reduces to one `existsSync`. If `anchorsIn` ever returned an
    // empty set for a real file, every fragment above would pass on nonsense.
    const readme = anchorsIn("README.md");
    expect(readme.has("mcp-server--check-before-you-fetch")).toBe(true);
    // The spelling this repository carried until LINK-quzdwhjt. It is dead on
    // GitLab, and the guard must say so.
    expect(readme.has("mcp-server-check-before-you-fetch")).toBe(false);
    expect(readme.has("no-such-heading-anywhere")).toBe(false);
  });

  it("`#` lines inside fenced code blocks are comments, not anchors", () => {
    // `packages/cli/README.md` opens a ```bash fence whose first line is
    // `# annotate a known shortener …` — a shell comment in column 1, which is
    // indistinguishable from an H1 to a regex that does not track fences.
    // GitLab renders no heading there, and neither may this.
    const anchors = anchorsIn("packages/cli/README.md");
    expect(anchors.has("usage")).toBe(true); // a real heading in the same file
    // `# @linklint/cli`: `@` and `/` are deleted with no separator left behind.
    expect(anchors.has("linklintcli")).toBe(true);
    expect(
      anchors.has("annotate-a-known-shortener-without-changing-what-the-score-says-about-it"),
      "a shell comment inside a fence became an anchor — fence tracking is broken, " +
        "and every fragment check downstream is now permissive in a way nobody chose.",
    ).toBe(false);
  });
});
